"""Schema integrity: models and migrations never drift; RLS covers every tenant table."""

from pathlib import Path

from alembic import command
from alembic.config import Config
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

from aura_db.models import TENANT_TABLES

INI = Path(__file__).resolve().parents[1] / "alembic.ini"


def test_models_match_migrations(pg_url: str) -> None:
    cfg = Config(str(INI))
    cfg.set_main_option("sqlalchemy.url", pg_url)
    command.check(cfg)  # raises AutogenerateDiffsDetected on drift


async def test_every_tenant_table_has_rls_and_policies(pg_url: str) -> None:
    engine = create_async_engine(pg_url)
    async with engine.connect() as conn:
        rls = dict(
            (
                await conn.execute(
                    text("SELECT tablename, rowsecurity FROM pg_tables WHERE schemaname='public'")
                )
            ).all()
        )
        policies = {
            (t, p)
            for t, p in (
                await conn.execute(text("SELECT tablename, policyname FROM pg_policies"))
            ).all()
        }
    await engine.dispose()
    for table in TENANT_TABLES:
        assert rls.get(table) is True, f"{table} has no row-level security"
        assert (table, "tenant_isolation") in policies, table
        assert (table, "system_access") in policies, table


# Tables aura_app may INSERT into but not SELECT from. Every server-generated column must
# have a client-side default (or an explicit column grant), or the ORM's
# INSERT ... RETURNING fails with "permission denied".
APP_INSERT_ONLY = {"audit_log": set(), "outbox": {"id"}, "jobs": set()}


def test_insert_only_tables_never_need_returning() -> None:
    from aura_db.base import Base

    for table_name, granted_columns in APP_INSERT_ONLY.items():
        table = Base.metadata.tables[table_name]
        for col in table.columns:
            if col.name in granted_columns:
                continue
            needs_server_value = col.server_default is not None or (
                col.primary_key and col.autoincrement is True
            )
            if needs_server_value:
                assert col.default is not None, (
                    f"{table_name}.{col.name} has only a server default; aura_app cannot "
                    "read it back via RETURNING. Add a client-side default."
                )
